// Since sodium 4, `flutter test` / `dart test` build and bundle libsodium for
// the host through the package's build hooks (native assets), so the crypto
// tests use the same library the SDK ships. These helpers load it once and
// hand it to the SDK. When it cannot be loaded (for example no C toolchain on
// the machine for the first build) the crypto tests are skipped.

import 'dart:convert';
import 'dart:io';

import 'package:catzconnect/src/core/sodium/server_crypto_io.dart';
import 'package:catzconnect/src/core/sodium/sodium_backend.dart';
import 'package:sodium/sodium.ffi.dart' show LibSodiumFFI;
import 'package:sodium/sodium_sumo.dart' as raw;

/// The loaded libsodium, or null when it could not be loaded.
class HostSodium {
  HostSodium(this.sumo, this.crypto);

  final raw.SodiumSumo sumo;
  final SodiumServerCrypto crypto;
}

HostSodium? _loaded;
bool _tried = false;

/// Loads libsodium once and installs it into the SDK
/// (`CatzSodium.debugOverride`). Returns null when it cannot be loaded.
Future<HostSodium?> installHostSodium() async {
  if (_tried) {
    if (_loaded != null) {
      CatzSodium.debugOverride(server: _loaded!.crypto, box: _loaded!.sumo);
    }
    return _loaded;
  }
  _tried = true;
  try {
    final raw.SodiumSumo sumo = await raw.SodiumSumoInit.init();
    final SodiumServerCrypto crypto = SodiumServerCrypto(sumo, const LibSodiumFFI());
    _loaded = HostSodium(sumo, crypto);
  } on Object catch (e) {
    stderr.writeln('libsodium not available for tests: $e');
    return null;
  }
  CatzSodium.debugOverride(server: _loaded!.crypto, box: _loaded!.sumo);
  return _loaded;
}

/// Why crypto tests were skipped.
const String kNoSodium = 'libsodium could not be built/loaded for the host (package:sodium build hooks; '
    'a C toolchain is needed for the first build)';

