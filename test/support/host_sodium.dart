// `flutter test` runs on the host without Flutter plugins, so sodium_libs'
// SodiumInit / SodiumSumoInit cannot load the bundled binary there. These
// helpers load a SYSTEM libsodium instead (Linux: `apt install libsodium23`,
// macOS: `brew install libsodium`, or point CATZ_LIBSODIUM at the file) and
// hand it to the SDK. Crypto tests are skipped when none is found.

import 'dart:convert';
import 'dart:ffi';
import 'dart:io';

import 'package:catzconnect/src/core/sodium/server_crypto_io.dart';
import 'package:catzconnect/src/core/sodium/sodium_backend.dart';
import 'package:sodium/sodium.ffi.dart' show LibSodiumFFI;
// VERIFY: in sodium 3.x, package:sodium/sodium_sumo.dart exports
// SodiumSumoInit.init(DynamicLibraryFactory) for the VM.
import 'package:sodium/sodium_sumo.dart' as raw;

/// The loaded host libsodium, or null when there is none.
class HostSodium {
  HostSodium(this.sumo, this.crypto);

  final raw.SodiumSumo sumo;
  final SodiumServerCrypto crypto;
}

DynamicLibrary? _open() {
  final List<String> candidates = <String>[
    if ((Platform.environment['CATZ_LIBSODIUM'] ?? '').isNotEmpty) Platform.environment['CATZ_LIBSODIUM']!,
    if (Platform.isLinux) ...<String>['libsodium.so.23', 'libsodium.so.26', 'libsodium.so'],
    if (Platform.isMacOS) ...<String>[
      '/opt/homebrew/lib/libsodium.dylib',
      '/usr/local/lib/libsodium.dylib',
      'libsodium.dylib',
    ],
    if (Platform.isWindows) 'libsodium.dll',
  ];
  for (final String c in candidates) {
    try {
      return DynamicLibrary.open(c);
    } on ArgumentError {
      // try the next one
    }
  }
  return null;
}

HostSodium? _loaded;
bool _tried = false;

/// Loads the host libsodium once and installs it into the SDK
/// (`CatzSodium.debugOverride`). Returns null when it is not installed.
Future<HostSodium?> installHostSodium() async {
  if (_tried) {
    if (_loaded != null) {
      CatzSodium.debugOverride(server: _loaded!.crypto, box: _loaded!.sumo);
    }
    return _loaded;
  }
  _tried = true;
  final DynamicLibrary? lib = _open();
  if (lib == null) return null;
  final raw.SodiumSumo sumo = await raw.SodiumSumoInit.init(() => lib);
  final SodiumServerCrypto crypto = SodiumServerCrypto(sumo, LibSodiumFFI(lib));
  _loaded = HostSodium(sumo, crypto);
  CatzSodium.debugOverride(server: crypto, box: sumo);
  return _loaded;
}

